/**
 * Offline seeds for the energy layer: one per energy company, built from its sourced AI / data-center link
 * (title = our summary of the cited article, NOT the publisher's headline; URL + date are the source's).
 * Used only when the live news refresher can't reach Google News.
 */
export const energySeedHeadlines: Headline[] = energyCompanies
  .filter((c) => c.aiLink)
  .map((c) => {
    const l = c.aiLink!;
    const first = l.summary.split(/(?<=\.)\s|;\s/)[0].replace(/\.$/, '');
    const title = `${c.name}: ${first.length > 150 ? first.slice(0, 147) + '…' : first}`;
    const mk = marketOfSegment(c.segment);
    return {
      id: `seed-ai-${c.id}`,
      title,
      source: l.source,
      url: l.url,
      publishedAt: `${l.date}T12:00:00Z`,
      tags: ['energy', 'data-center', c.id],
      companies: [c.id],
      markets: mk ? [mk] : [],
    };
  });
